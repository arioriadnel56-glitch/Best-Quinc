const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

function initialOf(name) {
  const c = String(name || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().charAt(0).toUpperCase();
  return G[c] ? c : 'B';
}

const cache = new Map();

// Icône PNG carrée : fond de la couleur de l'entreprise + initiale blanche.
// `maskable` réduit la lettre pour rester dans la zone de sécurité des icônes adaptatives.
function makeIcon(name, hexColor, size, maskable = false) {
  const initial = initialOf(name);
  const color = /^#[0-9a-fA-F]{6}$/.test(hexColor) ? hexColor : '#3E5C76';
  const key = `${initial}|${color}|${size}|${maskable}`;
  if (cache.has(key)) return cache.get(key);

  const r = parseInt(color.slice(1, 3), 16);
  const g = parseInt(color.slice(3, 5), 16);
  const b = parseInt(color.slice(5, 7), 16);
  const glyph = G[initial];
  const targetH = size * (maskable ? 0.36 : 0.5);
  const scale = Math.max(1, Math.floor(targetH / 7));
  const gw = 5 * scale, gh = 7 * scale;
  const ox = Math.floor((size - gw) / 2), oy = Math.floor((size - gh) / 2);

  const stride = size * 4 + 1;
  const raw = Buffer.alloc(stride * size);
  for (let y = 0; y < size; y++) {
    raw[y * stride] = 0;
    for (let x = 0; x < size; x++) {
      let on = false;
      if (x >= ox && x < ox + gw && y >= oy && y < oy + gh) {
        on = glyph[Math.floor((y - oy) / scale)][Math.floor((x - ox) / scale)] === '#';
      }
      const i = y * stride + 1 + x * 4;
      raw[i] = on ? 255 : r;
      raw[i + 1] = on ? 255 : g;
      raw[i + 2] = on ? 255 : b;
      raw[i + 3] = 255;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
  if (cache.size > 500) cache.clear();
  cache.set(key, png);
  return png;
}

